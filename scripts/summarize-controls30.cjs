'use strict';

// Aggregates the ledgers of scripts/verify-controls30.cjs into docs/control-sweep-30.md and
// artifacts/ipc/control-sweep30-summary.json. One result per declared control; the last
// recorded non-error result of a control counts.
// Usage: node scripts/summarize-controls30.cjs <label>[,<label>...]   (later labels override earlier ones per control)
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const ipc = path.join(root, 'artifacts', 'ipc');
const label = process.argv[2];
if (!label) throw new Error('usage: summarize-controls30.cjs <label>');
const ledgers = label.split(',').flatMap(one => fs.readdirSync(ipc).filter(name => name.startsWith(`control-sweep30-${one}-`) && name.endsWith('.jsonl')).sort());
const results = new Map(), context = {}, activation = {};
for (const name of ledgers) {
    for (const line of fs.readFileSync(path.join(ipc, name), 'utf8').split(/\r?\n/)) {
        if (!line.trim()) continue;
        const entry = JSON.parse(line);
        if (entry.step === 'context') { const ids = { ...(context.channelIds || {}), ...(entry.channelIds || {}) }; Object.assign(context, entry); context.channelIds = ids; }
        if (entry.step === 'project') context.project = entry;
        if (entry.step === 'page') activation[entry.page] = entry.activation;
        if (entry.step === 'bank') context.bank = entry.bank;
        if (entry.step === 'done') context.finalWindows = entry.windows;
        if (entry.step === 'control' && (entry.outcome !== 'sweep_error' || !results.has(entry.key))) results.set(entry.key, entry);
    }
}
const all = [...results.values()];
const symbol = { feedback_observed: '✓', not_observed: '·', unavailable: '×', read_only: 'r', action: 'a', rejected: '!', sweep_error: '?' };
const count = list => list.reduce((total, item) => { total[item.outcome] = (total[item.outcome] || 0) + 1; return total; }, {});
const pages = { main: all.filter(item => item.page === 'main'), mixer: all.filter(item => item.page === 'mixer') };
const summary = { generatedUtc: new Date().toISOString(), ledgers, context, activation, total: all.length, counts: { main: count(pages.main), mixer: count(pages.mixer) }, results: all };
fs.writeFileSync(path.join(ipc, 'control-sweep30-summary.json'), JSON.stringify(summary, null, 1));

const row = counts => ['feedback_observed', 'not_observed', 'unavailable', 'read_only', 'action', 'rejected', 'sweep_error'].map(key => counts[key] || 0).join(' | ');
const lines = [
    '# Binding controls: live sweep (session 30)', '',
    'Generated by `scripts/summarize-controls30.cjs` from the ledgers of `scripts/verify-controls30.cjs`; do not edit by hand.', '',
    `The sweep wrote every writable binding control of controller 3.14 once on the owned private-desktop Cubase AI 16.0.5.174 instance, through the real MCP server, and waited for host feedback (\`cubase_control_set\` with a settle window). A confirmed write was written back to the previous value. The project held ${(context.channels || []).length} mixer channels: ${(context.channels || []).join(', ')}. Selected-track controls were swept with the instrument channel selected.`, '',
    '| Page | confirmed by host feedback | no feedback | unavailable | read-only | action | rejected | error |', '| --- | --- | --- | --- | --- | --- | --- | --- |',
    `| main (${pages.main.length} controls) | ${row(summary.counts.main)} |`, `| mixer (${pages.mixer.length} controls) | ${row(summary.counts.mixer)} |`, '',
    '- **confirmed**: the host reported a new value for the control after the write.',
    '- **no feedback**: the write was submitted and the host reported nothing within 450 ms. For this build that means the bound host value does not exist for that channel type or edition (for example EQ on a MIDI channel, Control Room in Cubase AI), or it cannot change in this project state.',
    '- **unavailable**: the bridge already reports the control as unavailable: the host branch is missing, the bank slot has no channel, or no plug-in sits in the slot.',
    '- **read-only**: meters and other feedback-only values. **action**: host actions such as bank navigation; they report no value and were not triggered by the sweep.', '',
    `Page activation at sweep time: main ${JSON.stringify(activation.main || null)}; mixer ${JSON.stringify(activation.mixer || null)}. Unexpected windows after the sweep: ${JSON.stringify(context.finalWindows || [])}.`, ''
];
function family(key) {
    return key.replace(/^mixer\.channel\.\d+\./, 'mixer.channel.N.').replace(/\.(\d+)(?=\.|$)/g, '.#');
}
lines.push('## Main page', '', '| Control family | Controls | Result |', '| --- | --- | --- |');
const mainFamilies = new Map();
for (const item of pages.main) { const name = family(item.key); mainFamilies.set(name, (mainFamilies.get(name) || []).concat(item)); }
for (const [name, items] of mainFamilies) {
    const counts = count(items);
    lines.push(`| \`${name}\` | ${items.length} | ${Object.keys(counts).map(key => `${key.replace(/_/g, ' ')} ${counts[key]}`).join(', ')}${items.length === 1 && items[0].display !== undefined ? ` (display ${items[0].display})` : ''} |`);
}
lines.push('', '## Mixer page', '',
    'One column per channel that the bank reported for a slot while its control was written; the bank can show another channel in the same slot after the selection changes, so results are grouped by channel identity, not by slot number. `✓` confirmed, `·` no feedback, `×` unavailable, `r` read-only, `a` action. A cell with several controls shows the symbol and the count, or confirmed/total when they differ.', '');
const channelName = id => (context.channelIds || {})[id] ? context.channelIds[id].replace(/^(\w+?)(?:Channel)?:/, '$1: ') : 'channel outside the channel list';
const columns = [...new Set(pages.mixer.filter(item => item.channelUniqueId).map(item => item.channelUniqueId))];
// A slot whose reported identity changed while it was swept is named, so that doubled counts can be read correctly.
const changedSlots = [...new Set(pages.mixer.filter(item => item.channel !== undefined).map(item => item.channel))].sort((left, right) => left - right)
    .map(slot => ({ slot, ids: [...new Set(pages.mixer.filter(item => item.channel === slot && item.channelUniqueId).map(item => item.channelUniqueId))] }))
    .filter(item => item.ids.length > 1);
if (changedSlots.length) {
    lines.push(...changedSlots.map(item => `During the sweep the bank reported more than one channel for slot ${item.slot} without any bank action being triggered: ${item.ids.map(channelName).join(', then ')}. Controls of that slot are counted under the channel reported at the time of each write, so that channel can show twice the number of controls.`), '');
}
const emptySlots = [...new Set(pages.mixer.filter(item => item.channel !== undefined && !item.channelUniqueId).map(item => item.channel))].sort((a, b) => a - b);
lines.push(`| Control family | ${columns.map(channelName).join(' | ')} | slots without a channel (${emptySlots.join(', ')}) |`, `| --- | ${columns.map(() => '---').join(' | ')} | --- |`);
const cell = items => {
    if (!items.length) return '';
    if (items.length === 1) return symbol[items[0].outcome] || '?';
    const outcomes = [...new Set(items.map(item => item.outcome))];
    return outcomes.length === 1 ? `${symbol[outcomes[0]]} ×${items.length}` : `${items.filter(item => item.outcome === 'feedback_observed').length}/${items.length}`;
};
const mixerFamilies = new Map();
for (const item of pages.mixer) { const name = family(item.key); mixerFamilies.set(name, (mixerFamilies.get(name) || []).concat(item)); }
const global = [];
for (const [name, items] of mixerFamilies) {
    if (items.every(item => item.channel === undefined)) { global.push([name, items]); continue; }
    lines.push(`| \`${name}\` | ${columns.map(id => cell(items.filter(item => item.channelUniqueId === id))).join(' | ')} | ${cell(items.filter(item => item.channel !== undefined && !item.channelUniqueId))} |`);
}
if (global.length) {
    lines.push('', '| Control family without a bank slot | Controls | Result |', '| --- | --- | --- |');
    for (const [name, items] of global) { const counts = count(items); lines.push(`| \`${name}\` | ${items.length} | ${Object.keys(counts).map(key => `${key.replace(/_/g, ' ')} ${counts[key]}`).join(', ')} |`); }
}
lines.push('', '## Reading the results', '',
    '- A confirmed control is confirmed for the channel that sat in that bank slot, or for the selected instrument channel, in this project. Another channel type can behave differently.',
    '- "No feedback" is an observation, not an error path: the receipt of such a write says `confirmation.state: "not_observed"`.',
    '- Per-control detail (previous value, written value, reported value, display text): `artifacts/ipc/control-sweep30-summary.json`; raw ledgers `artifacts/ipc/control-sweep30-*.jsonl`.', '');
fs.writeFileSync(path.join(root, 'docs', 'control-sweep-30.md'), lines.join('\n'));
process.stdout.write(JSON.stringify({ ledgers: ledgers.length, total: all.length, counts: summary.counts }) + '\n');
